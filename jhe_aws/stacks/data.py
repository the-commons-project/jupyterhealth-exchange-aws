"""Everything that holds data: the KMS key, Postgres, the bundle bucket and the secrets.

Every resource here is retained on stack deletion (the database as a snapshot), so a teardown
of the other stacks never loses data. The database's security group lives here and admits
nothing by itself: each stack that runs a task adds its own ingress rule to it (the rule has to
be in the consuming stack, because this stack cannot depend on the stacks it serves).

Secrets (Secrets Manager, encrypted with the data key, retained):

    jhe/<env>/database         generated by RDS; the usual host/port/dbname/username/password
    jhe/<env>/service          created and filled by `jhe-deploy secrets init|set`, not by this
                               stack: SECRET_KEY, OIDC_RSA_PRIVATE_KEY, PATIENT_ACCESS_ENCRYPTION_KEYS,
                               SMTP_* and OW_S3_*
    jhe/<env>/mcp              likewise by the CLI: MCP_BROKER_KEY generated; JHE_CLIENT_ID and
                               JHE_CLIENT_SECRET set after the client is registered in JHE
    jhe/<env>/bootstrap-admin  the first admin's password, read by the ops task only
"""

from __future__ import annotations

import aws_cdk as cdk
from aws_cdk import aws_ec2 as ec2
from aws_cdk import aws_kms as kms
from aws_cdk import aws_rds as rds
from aws_cdk import aws_s3 as s3
from aws_cdk import aws_secretsmanager as sm
from cdk_nag import NagSuppressions
from constructs import Construct

from jhe_aws.config import EnvironmentConfig

from .network import NetworkStack, _retention

DATABASE_NAME = "jhe"
DATABASE_USER = "jhe"


class DataStack(cdk.Stack):
    def __init__(
        self, scope: Construct, construct_id: str, cfg: EnvironmentConfig, network: NetworkStack, **kwargs
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        self.cfg = cfg
        vpc = network.vpc

        self.key: kms.IKey | None = (
            kms.Key(
                self,
                "DataKey",
                alias=f"alias/jhe-{cfg.name}-data",
                description=f"JHE {cfg.name}: database, bucket and secrets",
                enable_key_rotation=True,
                removal_policy=cdk.RemovalPolicy.RETAIN,
            )
            if cfg.data.customer_managed_keys
            else None
        )

        self.database_sg = ec2.SecurityGroup(
            self,
            "DatabaseSecurityGroup",
            vpc=vpc,
            description=f"JHE {cfg.name} database: JHE tasks only (rules added by their stacks)",
            allow_all_outbound=False,
        )

        self.database = self._database(network)
        self.database_secret = self.database.secret
        assert self.database_secret is not None
        self.bundle_bucket = self._bucket()
        self.alb_logs_bucket = self._alb_logs_bucket()
        # jhe/<env>/service and jhe/<env>/mcp are deliberately NOT stack resources: CloudFormation
        # regenerates a secret's value on any change to how it is generated, which would empty
        # the fields an operator filled. `jhe-deploy secrets init` creates them under self.key,
        # and the task stacks reference them by name. They outlive every stack.
        self.bootstrap_admin_secret = sm.Secret(
            self,
            "BootstrapAdminSecret",
            secret_name=f"jhe/{cfg.name}/bootstrap-admin",
            description="The first admin's password; read by the ops task's createsuperuser only",
            encryption_key=self.key,
            generate_secret_string=sm.SecretStringGenerator(password_length=24, exclude_characters="\"'\\`$"),
            removal_policy=cdk.RemovalPolicy.RETAIN,
        )

        rotation = [
            {
                "id": "AwsSolutions-SMG4",
                "reason": "Rotation is a follow-on: the database secret can take the RDS rotator once "
                "the application has its own database role; the others hold keys JHE rotates "
                "by redeploying (Fernet key list, OIDC key) and values the operator sets.",
            }
        ]
        NagSuppressions.add_resource_suppressions(self.bootstrap_admin_secret, rotation)
        # `database.secret` is the attachment; the secret itself is its sibling resource
        NagSuppressions.add_resource_suppressions_by_path(
            self, f"/{self.stack_name}/Database/Secret/Resource", rotation
        )
        NagSuppressions.add_resource_suppressions_by_path(
            self,
            f"/{self.stack_name}/LogRetentionaae0aa3c5b4d4f87b02d85b201efdd8a",
            [
                {
                    "id": "AwsSolutions-IAM4",
                    "reason": "CDK's own log-retention Lambda for the Postgres log group.",
                },
                {
                    "id": "AwsSolutions-IAM5",
                    "reason": "CDK's own log-retention Lambda: logs:PutRetentionPolicy on *.",
                },
            ],
            apply_to_children=True,
        )

        cdk.CfnOutput(self, "DatabaseEndpoint", value=self.database.db_instance_endpoint_address)
        cdk.CfnOutput(self, "DatabaseInstanceIdentifier", value=self.database.instance_identifier)
        cdk.CfnOutput(self, "BundleBucketName", value=self.bundle_bucket.bucket_name)
        cdk.CfnOutput(self, "ServiceSecretName", value=f"jhe/{cfg.name}/service")
        cdk.CfnOutput(self, "McpSecretName", value=f"jhe/{cfg.name}/mcp")
        cdk.CfnOutput(self, "BootstrapAdminSecretName", value=f"jhe/{cfg.name}/bootstrap-admin")
        cdk.CfnOutput(self, "DatabaseSecurityGroupId", value=self.database_sg.security_group_id)

    def _database(self, network: NetworkStack) -> rds.DatabaseInstance:
        data = self.cfg.data
        engine = rds.DatabaseInstanceEngine.postgres(
            version=rds.PostgresEngineVersion.of(data.postgres_major_version, data.postgres_major_version)
        )
        parameters = rds.ParameterGroup(
            self,
            "DatabaseParameters",
            engine=engine,
            description=f"JHE {self.cfg.name}: TLS required",
            parameters={"rds.force_ssl": "1"},
        )
        database = rds.DatabaseInstance(
            self,
            "Database",
            instance_identifier=f"jhe-{self.cfg.name}-db",
            engine=engine,
            instance_type=ec2.InstanceType(data.instance_class.removeprefix("db.")),
            vpc=network.vpc,
            vpc_subnets=network.isolated_subnets,
            security_groups=[self.database_sg],
            credentials=rds.Credentials.from_generated_secret(
                DATABASE_USER, secret_name=f"jhe/{self.cfg.name}/database", encryption_key=self.key
            ),
            database_name=DATABASE_NAME,
            parameter_group=parameters,
            storage_encrypted=True,
            storage_encryption_key=self.key,
            allocated_storage=data.allocated_storage_gib,
            max_allocated_storage=data.max_allocated_storage_gib,
            storage_type=rds.StorageType.GP3,
            multi_az=data.multi_az,
            backup_retention=cdk.Duration.days(data.backup_retention_days),
            deletion_protection=data.deletion_protection,
            removal_policy=cdk.RemovalPolicy.SNAPSHOT,
            cloudwatch_logs_exports=["postgresql"],
            cloudwatch_logs_retention=_retention(data.log_retention_days),
            auto_minor_version_upgrade=True,
            ca_certificate=rds.CaCertificate.RDS_CA_RSA2048_G1,
            enable_performance_insights=False,
            publicly_accessible=False,
        )
        if database.secret is not None:
            database.secret.apply_removal_policy(cdk.RemovalPolicy.RETAIN)
        NagSuppressions.add_resource_suppressions(
            database,
            [
                {
                    "id": "AwsSolutions-RDS11",
                    "reason": "The default port, inside an isolated subnet admitting named groups only.",
                },
                {
                    "id": "AwsSolutions-RDS3",
                    "reason": "Multi-AZ is data.multi_az: off in the sandbox for cost, on in production.",
                },
                *(
                    []
                    if data.deletion_protection
                    else [
                        {
                            "id": "AwsSolutions-RDS10",
                            "reason": "Deletion protection is data.deletion_protection: on by default, "
                            "turned off by this configuration (the sandbox, which is torn down).",
                        }
                    ]
                ),
            ],
        )
        return database

    def _bucket(self) -> s3.Bucket:
        bucket = s3.Bucket(
            self,
            "BundleBucket",
            bucket_name=self.cfg.data.bundle_bucket_name,
            encryption=s3.BucketEncryption.KMS if self.key else s3.BucketEncryption.S3_MANAGED,
            encryption_key=self.key,
            bucket_key_enabled=bool(self.key),
            block_public_access=s3.BlockPublicAccess.BLOCK_ALL,
            enforce_ssl=True,
            versioned=True,
            lifecycle_rules=[
                # JHE uploads each pull as a multipart upload and aborts its own failures; this rule is
                # the backstop for a task that dies mid-upload, whose parts would otherwise stay (and be
                # billed) invisibly. Unconditional: it does not depend on version expiry being on.
                s3.LifecycleRule(
                    id="abort-incomplete-multipart-uploads",
                    abort_incomplete_multipart_upload_after=cdk.Duration.days(1),
                ),
                *(
                    [
                        s3.LifecycleRule(
                            id="expire-noncurrent-versions",
                            noncurrent_version_expiration=cdk.Duration.days(
                                self.cfg.data.bundle_noncurrent_version_days
                            ),
                        )
                    ]
                    if self.cfg.data.bundle_noncurrent_version_days
                    else []
                ),
            ],
            object_ownership=s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
            removal_policy=cdk.RemovalPolicy.RETAIN,
        )
        NagSuppressions.add_resource_suppressions(
            bucket,
            [
                {
                    "id": "AwsSolutions-S1",
                    "reason": "Object-level access is in CloudTrail data events when the account enables "
                    "them; server access logs would need a second bucket per environment.",
                }
            ],
        )
        return bucket

    def _alb_logs_bucket(self) -> s3.Bucket:
        """ALB access logs; the ALB's log delivery supports S3-managed encryption only. Here, not in
        the compute stack, so destroying compute never has to empty it."""
        bucket = s3.Bucket(
            self,
            "AlbAccessLogs",
            encryption=s3.BucketEncryption.S3_MANAGED,
            block_public_access=s3.BlockPublicAccess.BLOCK_ALL,
            enforce_ssl=True,
            object_ownership=s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
            lifecycle_rules=[s3.LifecycleRule(expiration=cdk.Duration.days(self.cfg.log_retention_days * 3))],
            removal_policy=cdk.RemovalPolicy.RETAIN,
        )
        NagSuppressions.add_resource_suppressions(
            bucket, [{"id": "AwsSolutions-S1", "reason": "This is the access-log bucket."}]
        )
        return bucket
